"""
inspectdb — introspect an existing PostgreSQL database and emit Model class definitions.

Usage (via CLI)::

    raftsql inspectdb                     # all public tables
    raftsql inspectdb auth_user items     # specific tables

Usage (programmatic)::

    import raftsql
    raftsql.setup()
    from raftsql.management.inspectdb import inspectdb
    inspectdb(raftsql._global_config)
"""
from __future__ import annotations

from typing import Any, List, Optional


# ---------------------------------------------------------------------------
# PostgreSQL data-type → RaftSQL field mapping
# ---------------------------------------------------------------------------
_PG_TYPE_MAP = {
    "integer":                      "IntegerField",
    "int4":                         "IntegerField",
    "bigint":                       "BigIntegerField",
    "int8":                         "BigIntegerField",
    "smallint":                     "SmallIntegerField",
    "int2":                         "SmallIntegerField",
    "real":                         "FloatField",
    "float4":                       "FloatField",
    "double precision":             "FloatField",
    "float8":                       "FloatField",
    "boolean":                      "BooleanField",
    "bool":                         "BooleanField",
    "text":                         "TextField",
    "character varying":            "CharField",
    "varchar":                      "CharField",
    "character":                    "CharField",
    "bpchar":                       "CharField",
    "numeric":                      "DecimalField",
    "decimal":                      "DecimalField",
    "timestamp without time zone":  "DateTimeField",
    "timestamp with time zone":     "DateTimeField",
    "timestamp":                    "DateTimeField",
    "date":                         "DateField",
    "time without time zone":       "TimeField",
    "time with time zone":          "TimeField",
    "json":                         "JSONField",
    "jsonb":                        "JSONField",
    "uuid":                         "UUIDField",
    "bytea":                        "BinaryField",
}


def inspectdb(config: Any, table_names: Optional[List[str]] = None) -> None:
    """Print Model class definitions for all (or selected) public tables."""
    from raftsql.db.connection import Connection

    with Connection(config) as conn:
        if table_names:
            tables = list(table_names)
        else:
            rows = conn.execute(
                "SELECT tablename FROM pg_tables "
                "WHERE schemaname = 'public' ORDER BY tablename",
                [],
                as_dict=True,
            )
            tables = [
                r["tablename"] for r in rows
                if r["tablename"] not in ("raftsql_migrations",)
            ]

        print("# Generated by RaftSQL inspectdb")
        print("# Paste into your models.py and review carefully before use.\n")
        print("from raftsql.orm import (")
        print("    Model, AutoField, IntegerField, BigIntegerField, SmallIntegerField,")
        print("    FloatField, DecimalField, BooleanField, CharField, TextField,")
        print("    DateField, DateTimeField, TimeField, JSONField, UUIDField, BinaryField,")
        print("    ForeignKey, CASCADE,")
        print(")\n")

        for tbl in tables:
            _emit_model(conn, tbl)


def _emit_model(conn: Any, table_name: str) -> None:
    """Emit a single Model class to stdout."""
    # Column metadata from information_schema
    col_rows = conn.execute(
        """
        SELECT column_name, data_type, character_maximum_length,
               is_nullable, column_default, numeric_precision, numeric_scale,
               ordinal_position
        FROM information_schema.columns
        WHERE table_name = %s AND table_schema = 'public'
        ORDER BY ordinal_position
        """,
        [table_name],
        as_dict=True,
    )

    # Primary key column(s)
    pk_rows = conn.execute(
        """
        SELECT a.attname
        FROM pg_index i
        JOIN pg_attribute a ON a.attrelid = i.indrelid AND a.attnum = ANY(i.indkey)
        WHERE i.indrelid = %s::regclass AND i.indisprimary
        """,
        [table_name],
        as_dict=True,
    )
    pk_cols = {r["attname"] for r in pk_rows}

    # Foreign-key info
    fk_rows = conn.execute(
        """
        SELECT
            kcu.column_name,
            ccu.table_name  AS foreign_table,
            ccu.column_name AS foreign_column
        FROM information_schema.table_constraints tc
        JOIN information_schema.key_column_usage kcu
            ON tc.constraint_name = kcu.constraint_name
           AND tc.table_schema = kcu.table_schema
        JOIN information_schema.referential_constraints rc
            ON tc.constraint_name = rc.constraint_name
        JOIN information_schema.constraint_column_usage ccu
            ON ccu.constraint_name = rc.unique_constraint_name
        WHERE tc.constraint_type = 'FOREIGN KEY' AND tc.table_name = %s
        """,
        [table_name],
        as_dict=True,
    )
    fk_map = {r["column_name"]: r for r in fk_rows}

    # CamelCase class name
    class_name = "".join(w.capitalize() for w in table_name.split("_"))

    print(f"\nclass {class_name}(Model):")
    print(f"    class Meta:")
    print(f"        db_table = '{table_name}'\n")

    for row in col_rows:
        col = row["column_name"]
        dtype = row["data_type"]
        nullable = row["is_nullable"] == "YES"
        max_len = row.get("character_maximum_length")
        default_val = row.get("column_default")
        num_prec = row.get("numeric_precision")
        num_scale = row.get("numeric_scale")
        is_pk = col in pk_cols
        is_autoincrement = bool(default_val and "nextval" in str(default_val))
        is_fk = col in fk_map

        if is_autoincrement and is_pk:
            print(f"    {col} = AutoField(primary_key=True)")
            continue

        if is_fk and col.endswith("_id"):
            fk_info = fk_map[col]
            ref_class = "".join(w.capitalize() for w in fk_info["foreign_table"].split("_"))
            kwargs = []
            if nullable:
                kwargs.append("null=True")
            kw_str = (", " + ", ".join(kwargs)) if kwargs else ""
            attr = col[:-3]  # strip _id suffix
            print(f"    {attr} = ForeignKey({ref_class!r}, on_delete=CASCADE{kw_str})")
            continue

        field_str = _map_field(dtype, is_pk, nullable, max_len, num_prec, num_scale, default_val)
        print(f"    {col} = {field_str}")

    print()


def _map_field(
    dtype: str,
    is_pk: bool,
    nullable: bool,
    max_len: Any,
    num_prec: Any,
    num_scale: Any,
    default_val: Any,
) -> str:
    field_cls = _PG_TYPE_MAP.get(dtype, None)
    kwargs: list = []

    if is_pk:
        kwargs.append("primary_key=True")
    if nullable:
        kwargs.append("null=True")

    if field_cls == "CharField":
        ml = int(max_len) if max_len else 255
        return f"CharField(max_length={ml}" + (", " + ", ".join(kwargs) if kwargs else "") + ")"

    if field_cls == "DecimalField":
        np = int(num_prec) if num_prec else 10
        ns = int(num_scale) if num_scale else 2
        base = f"DecimalField(max_digits={np}, decimal_places={ns}"
        return base + (", " + ", ".join(kwargs) if kwargs else "") + ")"

    if field_cls == "DateTimeField":
        if default_val and "CURRENT_TIMESTAMP" in str(default_val).upper():
            kwargs.append("auto_now_add=True")

    if field_cls:
        kw_str = ", ".join(kwargs)
        return f"{field_cls}({kw_str})" if kw_str else f"{field_cls}()"

    # Unknown type → TextField with comment
    kw_str = ", ".join(kwargs)
    comment = f"  # db_type: {dtype}"
    return (f"TextField({kw_str})" if kw_str else "TextField()") + comment
