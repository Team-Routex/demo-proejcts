"""
Build schema state by replaying migration files.

The "state" is the authoritative record of what the DB schema looks like
according to migration history — compared against current model definitions
by makemigrations to detect what has changed.

Returned structure
──────────────────
{
    "tables":  {table_name: {col_name: type_sql}},
    "indexes": {index_name: {"table": str, "columns": [...], "unique": bool}},
    "model_state": {table_name: {"fields": {attr_name: {"field_class", "col", "sql"}}}},
}

When a migration file contains a ``model_state`` variable (generated by
RaftSQL >= 2.x), ``build_state()`` uses that directly for the model-level
metadata required by accurate rename detection.  Older files that only have
``operations`` are still fully supported via SQL-replay (backward-compatible).
"""
import importlib.util
from typing import Dict, List

from .writer import list_migration_files, read_model_state


def build_state(migrations_dir: str) -> Dict:
    """
    Build schema state for *migrations_dir*.

    Strategy
    --------
    1. Walk files in numeric order.
    2. For each file, if it contains a ``model_state`` dict, adopt that as
       the authoritative ``model_state`` snapshot (it reflects the complete
       schema *after* that migration).  Also derive ``tables`` from it for
       SQL-level compat.
    3. For files without ``model_state`` (legacy), fall back to applying the
       ``operations`` list (SQL replay) as before.
    4. Always apply ``operations`` to keep ``indexes`` up to date (model_state
       does not track indexes yet).

    Returns
    -------
    {
        "tables":      {table_name: {col_name: type_sql}},
        "indexes":     {index_name: {"table": str, "columns": [...], "unique": bool}},
        "model_state": {table_name: {"fields": {attr_name: {"field_class","col","sql"}}}},
    }
    """
    state: Dict = {"tables": {}, "indexes": {}, "model_state": {}}
    for _num, _name, filepath in list_migration_files(migrations_dir):
        _apply_file_to_state(filepath, state)
    return state


def _apply_file_to_state(filepath: str, state: Dict) -> None:
    """Load a single migration file and mutate state in-place."""
    from .operations import (
        CreateTable, DropTable, RenameTable,
        AddColumn, DropColumn, RenameColumn, AlterColumn,
        AddIndex, DropIndex,
    )

    # ── 1. Load model_state snapshot if present (preferred) ───────────────
    ms = read_model_state(filepath)
    if ms is not None:
        # Adopt model_state as authoritative for table/column structure
        state["model_state"] = ms
        # Rebuild tables from model_state (SQL-level compat for runner/rollback)
        state["tables"] = {}
        for tbl, tbl_data in ms.items():
            tbl_cols = {
                fmeta["col"]: fmeta["sql"]
                for fmeta in tbl_data.get("fields", {}).values()
            }
            # Re-add __c__ sentinel entries so constraint diff keeps working
            for cname, csql in tbl_data.get("constraints", {}).items():
                tbl_cols[f"__c__{cname}"] = csql
            state["tables"][tbl] = tbl_cols
        # Still replay operations to keep indexes up to date
        _replay_ops_for_indexes(filepath, state)
        return

    # ── 2. Legacy file: pure SQL replay ───────────────────────────────────
    spec = importlib.util.spec_from_file_location("_raftsql_state_migration", filepath)
    if spec is None or spec.loader is None:
        return
    module = importlib.util.module_from_spec(spec)
    try:
        spec.loader.exec_module(module)
    except Exception:
        return

    for op in getattr(module, "operations", []):
        if isinstance(op, CreateTable):
            state["tables"][op.table_name] = dict(op.columns)

        elif isinstance(op, DropTable):
            state["tables"].pop(op.table_name, None)
            to_drop = [n for n, v in state["indexes"].items() if v["table"] == op.table_name]
            for name in to_drop:
                state["indexes"].pop(name)

        elif isinstance(op, RenameTable):
            if op.old_name in state["tables"]:
                state["tables"][op.new_name] = state["tables"].pop(op.old_name)
                for idx_data in state["indexes"].values():
                    if idx_data["table"] == op.old_name:
                        idx_data["table"] = op.new_name

        elif isinstance(op, AddColumn):
            if op.table_name in state["tables"]:
                state["tables"][op.table_name][op.column_name] = op.column_type

        elif isinstance(op, DropColumn):
            if op.table_name in state["tables"]:
                state["tables"][op.table_name].pop(op.column_name, None)

        elif isinstance(op, RenameColumn):
            tbl = state["tables"].get(op.table_name)
            if tbl and op.old_name in tbl:
                tbl[op.new_name] = tbl.pop(op.old_name)

        elif isinstance(op, AlterColumn):
            if op.table_name in state["tables"]:
                state["tables"][op.table_name][op.column_name] = op.new_type

        elif isinstance(op, AddIndex):
            name = op.index_name or _auto_index_name(op.table_name, op.column_names)
            state["indexes"][name] = {
                "table": op.table_name,
                "columns": list(op.column_names),
                "unique": op.unique,
            }

        elif isinstance(op, DropIndex):
            state["indexes"].pop(op.index_name, None)

        else:
            try:
                from .operations import AddConstraint, DropConstraint
            except ImportError:
                continue
            if isinstance(op, AddConstraint):
                if op.table_name in state["tables"]:
                    state["tables"][op.table_name][f"__c__{op.constraint_name}"] = op.constraint_sql
            elif isinstance(op, DropConstraint):
                if op.table_name in state["tables"]:
                    state["tables"][op.table_name].pop(f"__c__{op.constraint_name}", None)


def _replay_ops_for_indexes(filepath: str, state: Dict) -> None:
    """Replay only AddIndex/DropIndex operations from a file (used when model_state is present)."""
    from .operations import AddIndex, DropIndex
    spec = importlib.util.spec_from_file_location("_raftsql_idx_migration", filepath)
    if spec is None or spec.loader is None:
        return
    module = importlib.util.module_from_spec(spec)
    try:
        spec.loader.exec_module(module)
    except Exception:
        return
    for op in getattr(module, "operations", []):
        if isinstance(op, AddIndex):
            name = op.index_name or _auto_index_name(op.table_name, op.column_names)
            state["indexes"][name] = {
                "table": op.table_name,
                "columns": list(op.column_names),
                "unique": op.unique,
            }
        elif isinstance(op, DropIndex):
            state["indexes"].pop(op.index_name, None)



def _auto_index_name(table: str, columns: List[str]) -> str:
    return f"{table}_{'_'.join(columns)}_idx"


def build_state_before(migrations_dir: str, before_num: int) -> Dict:
    """
    Build schema state using only migrations with number < before_num.
    Used by rollback to recover the state that existed before a specific
    migration was applied, so reverse operations can be computed accurately.
    """
    state: Dict = {"tables": {}, "indexes": {}}
    for num, _name, filepath in list_migration_files(migrations_dir):
        if num >= before_num:
            break
        _apply_file_to_state(filepath, state)
    return state
